CREATE TABLE items (
    item_code VARCHAR(32) PRIMARY KEY,
    description VARCHAR(512) NOT NULL,
    uom VARCHAR(16) NOT NULL,
    category VARCHAR(128) NOT NULL,
    item_type VARCHAR(32) NOT NULL,
    standard_price NUMERIC(18,4) NOT NULL
);

CREATE TABLE suppliers (
    supplier_id VARCHAR(16) PRIMARY KEY,
    name VARCHAR(256) NOT NULL,
    city VARCHAR(128),
    categories VARCHAR(1024),
    status VARCHAR(32) NOT NULL,
    on_time_pct NUMERIC(8,2),
    quality_rating NUMERIC(4,2)
);

CREATE TABLE plants (
    code VARCHAR(16) PRIMARY KEY,
    name VARCHAR(128) NOT NULL
);

CREATE TABLE po_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    po_number VARCHAR(32) NOT NULL,
    po_date DATE NOT NULL,
    supplier_id VARCHAR(16) NOT NULL,
    item_code VARCHAR(32) NOT NULL,
    quantity NUMERIC(18,4) NOT NULL,
    uom VARCHAR(16) NOT NULL,
    unit_price NUMERIC(18,4) NOT NULL,
    plant VARCHAR(16) NOT NULL,
    delivered_on_time BOOLEAN
);

CREATE INDEX idx_po_history_item_date ON po_history (item_code, po_date);
CREATE INDEX idx_po_history_supplier ON po_history (supplier_id);

CREATE TABLE item_aliases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alias VARCHAR(128) NOT NULL,
    canonical_term VARCHAR(128) NOT NULL,
    language VARCHAR(16),
    source VARCHAR(64)
);

CREATE UNIQUE INDEX uq_item_alias ON item_aliases (alias);

CREATE TABLE contracts (
    contract_id VARCHAR(32) PRIMARY KEY,
    supplier_id VARCHAR(16) NOT NULL,
    supplier_name VARCHAR(256),
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    value_cap NUMERIC(18,2) NOT NULL,
    consumed_value NUMERIC(18,2) NOT NULL,
    source VARCHAR(64),
    status VARCHAR(32)
);

CREATE TABLE contract_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_id VARCHAR(32) NOT NULL,
    item_code VARCHAR(32) NOT NULL,
    description VARCHAR(512),
    uom VARCHAR(16),
    rate NUMERIC(18,4) NOT NULL
);

CREATE INDEX idx_contract_lines_contract ON contract_lines (contract_id);
CREATE INDEX idx_contract_lines_item ON contract_lines (item_code);

CREATE TABLE contract_consumption_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id VARCHAR(64) NOT NULL,
    contract_id VARCHAR(32) NOT NULL,
    requirement_id BIGINT,
    amount NUMERIC(18,2) NOT NULL
);

CREATE TABLE batch_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_key VARCHAR(128) NOT NULL,
    filename VARCHAR(512),
    input_hash VARCHAR(128) NOT NULL,
    policy_version_label VARCHAR(64),
    uploaded_by VARCHAR(128),
    created_at TIMESTAMP NOT NULL,
    result_json TEXT
);

CREATE UNIQUE INDEX uq_batch_run_key ON batch_runs (run_key);

CREATE TABLE pr_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT,
    filename VARCHAR(512),
    uploaded_by VARCHAR(128),
    uploaded_at TIMESTAMP NOT NULL,
    input_hash VARCHAR(128) NOT NULL
);

CREATE TABLE pr_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT,
    pr_no VARCHAR(64) NOT NULL,
    pr_line INTEGER NOT NULL,
    created_at TIMESTAMP NOT NULL,
    requester VARCHAR(128),
    department VARCHAR(128),
    plant VARCHAR(16),
    raw_item_code VARCHAR(64),
    raw_description VARCHAR(1024),
    quantity NUMERIC(18,4),
    raw_uom VARCHAR(16),
    estimated_unit_price NUMERIC(18,4),
    need_by_date DATE,
    urgency VARCHAR(32),
    resolved_item_code VARCHAR(32),
    match_score NUMERIC(8,4),
    match_method VARCHAR(64),
    validation_status VARCHAR(64)
);

CREATE INDEX idx_pr_lines_batch ON pr_lines (batch_id);

CREATE TABLE requirements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT,
    requirement_date DATE NOT NULL,
    first_created_at TIMESTAMP NOT NULL,
    item_code VARCHAR(32),
    plant VARCHAR(16),
    urgency VARCHAR(32),
    contract_id VARCHAR(32),
    unit_price NUMERIC(18,4),
    value NUMERIC(18,2),
    valuation_source VARCHAR(128),
    is_new_item BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE requirement_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requirement_id BIGINT NOT NULL,
    pr_line_id BIGINT NOT NULL
);

CREATE INDEX idx_requirement_lines_req ON requirement_lines (requirement_id);
CREATE INDEX idx_requirement_lines_line ON requirement_lines (pr_line_id);

CREATE TABLE decisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT,
    requirement_id BIGINT,
    decision VARCHAR(32),
    route VARCHAR(32),
    supplier_id VARCHAR(16),
    unit_price NUMERIC(18,4),
    group_value_inr NUMERIC(18,2),
    suggested_supplier_ids VARCHAR(1024),
    policy_version VARCHAR(64),
    clause VARCHAR(64),
    source_reference VARCHAR(512),
    reason TEXT,
    trace_json TEXT
);

CREATE INDEX idx_decisions_run ON decisions (run_id);
CREATE INDEX idx_decisions_requirement ON decisions (requirement_id);

CREATE TABLE decision_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    decision_id BIGINT NOT NULL,
    pr_line_id BIGINT NOT NULL
);

CREATE INDEX idx_decision_lines_decision ON decision_lines (decision_id);

CREATE TABLE preferred_supplier_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_code VARCHAR(32) NOT NULL,
    as_of_date DATE NOT NULL,
    policy_version VARCHAR(64),
    rank INTEGER NOT NULL,
    supplier_id VARCHAR(16) NOT NULL,
    score NUMERIC(18,6) NOT NULL,
    score_components TEXT,
    reference_price NUMERIC(18,4),
    has_contract BOOLEAN NOT NULL,
    po_count INTEGER NOT NULL,
    recency_bucket VARCHAR(32)
);

CREATE INDEX idx_preferred_item_date ON preferred_supplier_snapshots (item_code, as_of_date);

CREATE TABLE pos (
    po_id VARCHAR(32) PRIMARY KEY,
    supplier_id VARCHAR(16) NOT NULL,
    plant VARCHAR(16) NOT NULL,
    route VARCHAR(32) NOT NULL,
    created_from_requirement BIGINT,
    first_requirement_at TIMESTAMP NOT NULL
);

CREATE TABLE po_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    po_id VARCHAR(32) NOT NULL,
    requirement_id BIGINT NOT NULL
);

CREATE INDEX idx_po_lines_po ON po_lines (po_id);

CREATE TABLE sourcing_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route VARCHAR(32),
    requirement_id BIGINT,
    suggested_supplier_ids VARCHAR(1024),
    approval_status VARCHAR(32)
);

CREATE TABLE policy_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_version_id BIGINT,
    label VARCHAR(64) NOT NULL,
    document_ref VARCHAR(512),
    effective_from DATE NOT NULL,
    status VARCHAR(32) NOT NULL,
    source VARCHAR(32) NOT NULL,
    content_hash VARCHAR(128) NOT NULL,
    approved_by VARCHAR(128),
    approved_at TIMESTAMP,
    activated_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL,
    notes TEXT
);

CREATE UNIQUE INDEX uq_policy_label ON policy_versions (label);

CREATE TABLE policy_facts (
    fact_key VARCHAR(64) PRIMARY KEY,
    value_type VARCHAR(32) NOT NULL,
    resolver_key VARCHAR(64) NOT NULL,
    config_json TEXT,
    description VARCHAR(1024),
    is_available BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE policy_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id BIGINT NOT NULL,
    rule_key VARCHAR(64) NOT NULL,
    priority INTEGER NOT NULL,
    clause_ref VARCHAR(64),
    name VARCHAR(256),
    scope_json TEXT,
    condition_json TEXT NOT NULL,
    outcome_json TEXT NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE UNIQUE INDEX uq_policy_rule_key ON policy_rules (version_id, rule_key);
CREATE UNIQUE INDEX uq_policy_rule_priority ON policy_rules (version_id, priority);
CREATE INDEX idx_policy_rules_version ON policy_rules (version_id);

CREATE TABLE policy_parameters (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id BIGINT NOT NULL,
    param_key VARCHAR(64) NOT NULL,
    value_json TEXT NOT NULL,
    value_type VARCHAR(32) NOT NULL,
    scope_json TEXT
);

CREATE UNIQUE INDEX uq_policy_parameter ON policy_parameters (version_id, param_key, scope_json);
CREATE INDEX idx_policy_parameters_version ON policy_parameters (version_id);

CREATE TABLE policy_amendments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source VARCHAR(32) NOT NULL,
    raw_text TEXT,
    document_ref VARCHAR(512),
    extracted_json TEXT,
    operations_json TEXT,
    diff_json TEXT,
    status VARCHAR(32) NOT NULL,
    effective_from DATE,
    created_by VARCHAR(128),
    approved_by VARCHAR(128),
    approved_at TIMESTAMP,
    applied_version_id BIGINT,
    applied_at TIMESTAMP
);

CREATE TABLE policy_change_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id BIGINT,
    operation VARCHAR(64),
    target VARCHAR(128),
    before_json TEXT,
    after_json TEXT,
    actor VARCHAR(128),
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(64) NOT NULL,
    display_name VARCHAR(128),
    role VARCHAR(32) NOT NULL
);

CREATE UNIQUE INDEX uq_users_username ON users (username);

CREATE TABLE audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor VARCHAR(128),
    action VARCHAR(128) NOT NULL,
    target VARCHAR(128),
    before_json TEXT,
    after_json TEXT,
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE chat_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_key VARCHAR(64) NOT NULL,
    requester VARCHAR(128),
    department VARCHAR(128),
    created_at TIMESTAMP NOT NULL
);

CREATE UNIQUE INDEX uq_chat_session_key ON chat_sessions (session_key);

CREATE TABLE chat_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL,
    role VARCHAR(32) NOT NULL,
    content TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL
);
